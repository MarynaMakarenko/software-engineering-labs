-- JobMatch: схема БД (H2 у режимі PostgreSQL / PostgreSQL 16)

CREATE TABLE user_account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('CANDIDATE', 'EMPLOYER', 'RECRUITER')),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE company (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT UNIQUE REFERENCES user_account (id) ON DELETE SET NULL,
    name          VARCHAR(120)  NOT NULL UNIQUE,
    city          VARCHAR(60)   NOT NULL,
    address       VARCHAR(200)  NOT NULL,
    phone         VARCHAR(13)   NOT NULL,
    email         VARCHAR(100)  NOT NULL,
    website       VARCHAR(200),
    description   VARCHAR(2000)
);

CREATE TABLE person (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT UNIQUE REFERENCES user_account (id) ON DELETE SET NULL,
    last_name        VARCHAR(50)  NOT NULL,
    first_name       VARCHAR(50)  NOT NULL,
    middle_name      VARCHAR(50),
    birth_date       DATE,
    phone            VARCHAR(13)  NOT NULL,
    email            VARCHAR(100) NOT NULL,
    city             VARCHAR(60)  NOT NULL,
    home_address     VARCHAR(200),
    job_status       VARCHAR(20)  NOT NULL CHECK (job_status IN ('SEARCHING', 'NOT_SEARCHING')),
    desired_position VARCHAR(100),
    desired_salary   INTEGER CHECK (desired_salary BETWEEN 1000 AND 1000000),
    about            VARCHAR(1000),
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_person_status ON person (job_status);
CREATE INDEX idx_person_last_name ON person (last_name);

CREATE TABLE education (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id       BIGINT       NOT NULL REFERENCES person (id) ON DELETE CASCADE,
    level           VARCHAR(20)  NOT NULL CHECK (level IN ('SECONDARY', 'VOCATIONAL', 'BACHELOR', 'MASTER', 'PHD')),
    institution     VARCHAR(150) NOT NULL,
    specialty       VARCHAR(100) NOT NULL,
    graduation_year INTEGER      NOT NULL CHECK (graduation_year BETWEEN 1950 AND 2035)
);
CREATE INDEX idx_education_person ON education (person_id);

CREATE TABLE work_record (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id    BIGINT       NOT NULL REFERENCES person (id) ON DELETE CASCADE,
    company_id   BIGINT REFERENCES company (id) ON DELETE SET NULL,
    company_name VARCHAR(120) NOT NULL,
    position     VARCHAR(100) NOT NULL,
    salary       INTEGER CHECK (salary BETWEEN 0 AND 1000000),
    start_date   DATE         NOT NULL,
    end_date     DATE,
    CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX idx_work_person ON work_record (person_id);

CREATE TABLE vacancy (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id                BIGINT        NOT NULL REFERENCES company (id) ON DELETE CASCADE,
    position                  VARCHAR(100)  NOT NULL,
    salary                    INTEGER       NOT NULL CHECK (salary BETWEEN 1000 AND 1000000),
    required_education        VARCHAR(20) CHECK (required_education IN ('SECONDARY', 'VOCATIONAL', 'BACHELOR', 'MASTER', 'PHD')),
    required_experience_years INTEGER       NOT NULL CHECK (required_experience_years BETWEEN 0 AND 40),
    requirements              VARCHAR(2000),
    city                      VARCHAR(60)   NOT NULL,
    status                    VARCHAR(10)   NOT NULL CHECK (status IN ('OPEN', 'CLOSED')),
    created_at                TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_vacancy_status ON vacancy (status);

CREATE TABLE application (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vacancy_id BIGINT      NOT NULL REFERENCES vacancy (id) ON DELETE CASCADE,
    person_id  BIGINT      NOT NULL REFERENCES person (id) ON DELETE CASCADE,
    source     VARCHAR(20) NOT NULL CHECK (source IN ('CANDIDATE', 'RECRUITER')),
    status     VARCHAR(20) NOT NULL CHECK (status IN ('NEW', 'INVITED', 'REJECTED', 'HIRED')),
    comment    VARCHAR(500),
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_application UNIQUE (vacancy_id, person_id)
);
